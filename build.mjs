// Builds the site into dist/ for Cloudflare Pages.
// Copies everything as-is, then turns the photos in assets/photography/ into
// web-sized copies plus photography/photos.js (the list the photography page reads).
// Run locally with:  npm install && npm run build

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const DIST = path.join(ROOT, "dist");
const PHOTOS_SRC = path.join(ROOT, "assets", "photography");
const PHOTOS_OUT = path.join(DIST, "assets", "photography");
const WIDTHS = [640, 1280, 2000];
const IMAGE_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".tif", ".tiff", ".avif"]);

// Not copied to the live site
const SKIP = new Set(["dist", "node_modules", ".git", ".github", "package.json",
  "package-lock.json", "build.mjs", ".node-version", ".gitignore"]);

const warn = (msg) => console.warn("⚠  " + msg);

async function copySite(from, to) {
  await fs.mkdir(to, { recursive: true });
  for (const entry of await fs.readdir(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    if (from === ROOT && SKIP.has(entry.name)) continue;
    if (src === PHOTOS_SRC) continue;                       // handled below
    if (entry.isDirectory()) await copySite(src, path.join(to, entry.name));
    else await fs.copyFile(src, path.join(to, entry.name));
  }
}

// "IMG_0042_big.JPG" -> { key: "img_0042", size: "big" }
function parseName(file) {
  const stem = path.parse(file).name;
  const m = stem.match(/^(.*?)[_-](med|big)$/i);
  const base = m ? m[1] : stem;
  return { base, key: base.toLowerCase(), size: m ? m[2].toLowerCase() : null };
}

async function readCaptions() {
  const captions = new Map();
  let text;
  try { text = await fs.readFile(path.join(PHOTOS_SRC, "captions.txt"), "utf8"); }
  catch { return captions; }
  text.split(/\r?\n/).forEach((line, i) => {
    line = line.trim();
    if (!line || line.startsWith("#")) return;
    const colon = line.indexOf(":");
    if (colon < 1) { warn(`captions.txt line ${i + 1} has no "filename: caption" — skipped`); return; }
    const name = line.slice(0, colon).trim();
    const caption = line.slice(colon + 1).trim();
    if (caption) captions.set(parseName(name).key, { caption, name, used: false });
  });
  return captions;
}

async function buildPhotos() {
  await fs.mkdir(PHOTOS_OUT, { recursive: true });
  let files = [];
  try { files = await fs.readdir(PHOTOS_SRC); } catch { /* no folder yet */ }

  const images = [];
  for (const file of files) {
    const ext = path.extname(file).toLowerCase();
    if (IMAGE_EXT.has(ext)) images.push(file);
    else if (ext === ".heic" || ext === ".heif") warn(`${file}: HEIC isn't supported — export it as JPG`);
  }
  images.sort((a, b) => parseName(a).base.localeCompare(parseName(b).base, undefined, { numeric: true }));

  const captions = await readCaptions();
  const usedSlugs = new Set();
  const list = [];

  for (const file of images) {
    const { base, key, size } = parseName(file);
    const input = path.join(PHOTOS_SRC, file);
    let meta;
    try { meta = await sharp(input).metadata(); }
    catch { warn(`${file}: couldn't read this image — skipped`); continue; }

    // phone photos are often stored sideways with a "rotate me" flag
    const turned = (meta.orientation || 1) >= 5;
    const w = turned ? meta.height : meta.width;
    const h = turned ? meta.width : meta.height;

    let slug = base.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "photo";
    while (usedSlugs.has(slug)) slug += "-2";
    usedSlugs.add(slug);

    const srcset = [];
    for (const target of WIDTHS) {
      const width = Math.min(target, w);
      const out = `${slug}-${width}.jpg`;
      await sharp(input).rotate().resize({ width }).jpeg({ quality: 82, mozjpeg: true })
        .toFile(path.join(PHOTOS_OUT, out));
      srcset.push(`../assets/photography/${out} ${width}w`);
      if (width === w) break;                                // photo smaller than the next size
    }

    const entry = { src: srcset[Math.min(1, srcset.length - 1)].split(" ")[0],
                    srcset: srcset.join(", "), w, h };
    if (size) entry.size = size;
    const cap = captions.get(key);
    if (cap) { entry.caption = cap.caption; cap.used = true; }
    list.push(entry);
    console.log(`  ${file}${size ? `  [${size}]` : ""}${cap ? "  + caption" : ""}`);
  }

  for (const cap of captions.values())
    if (!cap.used) warn(`captions.txt mentions "${cap.name}" but there's no photo with that name`);

  await fs.mkdir(path.join(DIST, "photography"), { recursive: true });
  await fs.writeFile(path.join(DIST, "photography", "photos.js"),
    "// Generated by build.mjs — don't edit.\nwindow.PHOTOS = " + JSON.stringify(list, null, 1) + ";\n");
  console.log(`Photography: ${list.length} photo(s).`);
}

await fs.rm(DIST, { recursive: true, force: true });
await copySite(ROOT, DIST);
await buildPhotos();
console.log("Built site into dist/");
